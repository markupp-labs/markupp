require "test_helper"

# Favicon do mascote (script/mascot.rb) no lugar do círculo vermelho padrão do Rails.
class FaviconTest < ActionDispatch::IntegrationTest
  test "the pages link the mascot icons" do
    get new_session_path

    assert_select "link[rel=icon][type='image/svg+xml'][href='/favicon.svg']"
    assert_select "link[rel=icon][type='image/png'][sizes='32x32'][href='/favicon-32.png']"
    assert_select "link[rel=apple-touch-icon][sizes='180x180'][href='/apple-touch-icon.png']"
  end

  test "the svg icon is the mascot in braille dots, not the default red circle" do
    path = Rails.public_path.join("favicon.svg")
    assert path.exist?, "expected #{path} generated by script/mascot.rb"
    svg = path.read

    assert_operator Nokogiri::XML(svg).css("circle").size, :>, 100
    assert_not_includes svg, 'fill="red"'
  end

  # Endereços novos: o navegador guarda o favicon por muito tempo, e o vermelho padrão morava em /icon.svg e /icon.png.
  test "the default rails icons are gone and the browser fallback favicon.ico is the mascot" do
    assert_not Rails.public_path.join("icon.svg").exist?
    assert_not Rails.public_path.join("icon.png").exist?
    assert Rails.public_path.join("favicon.ico").exist?, "expected favicon.ico generated by script/mascot.rb"
    assert_equal [ 0, 1 ], Rails.public_path.join("favicon.ico").binread[0, 4].unpack("vv"), "favicon.ico should be an ICO file"
  end

  test "the png icons exist in their sizes" do
    { "favicon-32.png" => 32, "apple-touch-icon.png" => 180 }.each do |name, size|
      path = Rails.public_path.join(name)
      assert path.exist?, "expected #{path} generated by script/mascot.rb"
      assert_equal [ size, size ], path.binread[16, 8].unpack("NN"), "#{name} should be #{size}x#{size}"
    end
  end
end
